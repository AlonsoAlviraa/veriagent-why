"""PDF export of the decision memo (fpdf2, core fonts)."""
from __future__ import annotations
from pathlib import Path

REPL = {"×": "x", "–": "-", "—": "-", "→": "->", "≤": "<=", "≥": ">=", "·": "*", "’": "'", "“": '"', "”": '"', "−": "-"}


def _latin(s: str) -> str:
    for a, b in REPL.items():
        s = s.replace(a, b)
    return s.encode("latin-1", "replace").decode("latin-1")


def memo_pdf(md: str, out: Path) -> Path:
    from fpdf import FPDF
    pdf = FPDF(format="A4")
    pdf.set_auto_page_break(True, 15)
    pdf.add_page()
    pdf.set_font("Helvetica", "B", 9)
    pdf.set_text_color(160, 0, 0)
    pdf.multi_cell(0, 5, "SYNTHETIC DATA - generated by VeriAgent Why. Every finding below passed the deterministic Claim Gate.", new_x="LMARGIN", new_y="NEXT")
    pdf.set_text_color(0, 0, 0)
    for line in md.splitlines():
        t = _latin(line.replace("**", ""))
        if line.startswith("# "):
            pdf.set_font("Helvetica", "B", 15); pdf.multi_cell(0, 8, t[2:], new_x="LMARGIN", new_y="NEXT"); pdf.ln(1)
        elif line.startswith("## "):
            pdf.ln(2); pdf.set_font("Helvetica", "B", 12); pdf.multi_cell(0, 7, t[3:], new_x="LMARGIN", new_y="NEXT")
        elif not line.strip():
            pdf.ln(2)
        else:
            pdf.set_font("Helvetica", "", 10); pdf.multi_cell(0, 5, t, new_x="LMARGIN", new_y="NEXT")
    pdf.output(str(out))
    return out
