"""Seeded, deterministic generator for the SYNTHETIC, LABELLED e-commerce dataset.

All rows are synthetic (generated by this script). Nothing here is real customer data.
Writes a DuckDB snapshot with 5 views (v_orders, v_returns, v_tickets, v_logistics,
v_promotions) and the ground truth to eval/ground_truth.json. Agents never read the
ground truth; only the eval harness does.

Scenario "demo_ontime" (planted):
  KPI: on-time delivery rate, baseline 2026-09-15..2026-09-30 vs period 2026-10-01..2026-10-14.
  Planted cause: carrier "CarrierB" breaches its SLA in region "North" during the period.
  Trap: promotion "PROMO-HOME-SOUTH" runs exactly during the period, but on category
        "home" in region "South", which does not overlap with the late shipments.
Usage: python scripts/make_data.py [--seed 42] [--out data/snapshot.duckdb]
"""
from __future__ import annotations
import argparse, json, random
from datetime import date, timedelta
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REGIONS = ["North", "South", "East", "West"]
CATEGORIES = ["electronics", "home", "apparel", "beauty"]
CARRIERS = ["CarrierA", "CarrierB", "CarrierC"]
BASELINE = (date(2026, 9, 15), date(2026, 9, 30))
PERIOD = (date(2026, 10, 1), date(2026, 10, 14))
LATE_TEXT = ["My parcel is late, tracking has not moved", "Delivery delayed again, where is my order",
             "Package still not delivered past the promised date", "Courier missed the delivery window"]
OTHER_TEXT = ["Can I change my delivery address", "Question about sizing", "Discount code not applied",
              "Item arrived damaged", "How do I return this item", "Invoice request"]
PROMO = {"promo_id": "PROMO-HOME-SOUTH", "name": "Home week South", "start_date": PERIOD[0],
         "end_date": PERIOD[1], "category": "home", "region": "South", "discount_pct": 20.0}


DEMO_SCENARIO = {"breach": {"carrier": "CarrierB", "region": "North", "p": 0.55},
                 "promo": {"category": "home", "region": "South", "causes_late": False}, "seasonal_p": None}


def generate(seed: int = 42, scenario: dict | None = None) -> dict[str, list[dict]]:
    sc = DEMO_SCENARIO if scenario is None else scenario
    pr = sc.get("promo")
    promo_row = None
    if pr:
        promo_row = {"promo_id": f"PROMO-{pr['category'].upper()}-{pr['region'].upper()}", "name": f"{pr['category'].title()} week {pr['region']}",
                     "start_date": PERIOD[0], "end_date": PERIOD[1], "category": pr["category"], "region": pr["region"], "discount_pct": 20.0}
    rng = random.Random(seed)
    orders, logi, returns, tickets = [], [], [], []
    d, n = BASELINE[0], 0
    while d <= PERIOD[1]:
        in_period = d >= PERIOD[0]
        for _ in range(rng.randint(55, 65)):
            n += 1
            region, cat, carrier = rng.choice(REGIONS), rng.choice(CATEGORIES), rng.choice(CARRIERS)
            promo = None
            demand_boost = False
            if in_period and pr and cat == pr["category"] and region == pr["region"]:
                promo, demand_boost = promo_row["promo_id"], True
            qty = rng.randint(1, 3) + (1 if demand_boost else 0)
            price = round(rng.uniform(15, 120), 2)
            disc = 0.8 if promo else 1.0
            oid = f"O{n:06d}"
            orders.append({"order_id": oid, "order_date": d, "region": region, "category": cat,
                           "sku": f"SKU-{cat[:3].upper()}-{rng.randint(1, 40):03d}", "qty": qty,
                           "revenue": round(qty * price * disc, 2), "cost": round(qty * price * 0.6, 2),
                           "promo_id": promo})
            p_late = 0.06
            b = sc.get("breach")
            if in_period and b and carrier == b["carrier"] and region == b["region"]:
                p_late = b["p"]  # planted SLA breach
            if in_period and sc.get("seasonal_p"):
                p_late = sc["seasonal_p"]  # planted uniform (calendar) rise across all segments
            if in_period and promo and pr.get("causes_late"):
                p_late = 0.5  # planted promotion effect: demand overload on promo orders
            late = rng.random() < p_late
            promised = 3
            actual = promised + (rng.randint(2, 5) if late else rng.randint(-1, 0))
            logi.append({"shipment_id": f"S{n:06d}", "order_id": oid, "carrier": carrier, "region": region,
                         "ship_date": d, "promised_days": promised, "actual_days": actual,
                         "on_time": actual <= promised})
            if rng.random() < (0.35 if late else 0.03):
                tickets.append({"ticket_id": f"T{len(tickets)+1:06d}", "order_id": oid,
                                "created_date": d + timedelta(days=actual),
                                "text": rng.choice(LATE_TEXT if late else OTHER_TEXT)})
            if rng.random() < (0.12 if late else 0.05):
                returns.append({"return_id": f"R{len(returns)+1:06d}", "order_id": oid,
                                "return_date": d + timedelta(days=actual + rng.randint(1, 5)),
                                "reason": "late_delivery" if late and rng.random() < 0.7 else rng.choice(["size", "damaged", "changed_mind"])})
        d += timedelta(days=1)
    return {"orders": orders, "logistics": logi, "returns": returns, "tickets": tickets, "promotions": [promo_row] if promo_row else []}


GROUND_TRUTH = {
    "_note": "Planted by scripts/make_data.py. Read ONLY by the eval harness, never by agents.",
    "scenarios": [{"scenario_id": "demo_ontime", "kpi": "on_time_rate",
                   "baseline": [str(BASELINE[0]), str(BASELINE[1])], "period": [str(PERIOD[0]), str(PERIOD[1])],
                   "top_cause_label": "carrier_sla_breach", "segment": {"carrier": "CarrierB", "region": "North"},
                   "trap": {"type": "promotion", "promo_id": PROMO["promo_id"], "why_not": "dates match, but category/region do not overlap the late shipments"},
                   "split": "demo (excluded from test)"}],
}


def write_duckdb(tables: dict, out: Path) -> None:
    import duckdb
    out.parent.mkdir(parents=True, exist_ok=True)
    if out.exists():
        out.unlink()
    con = duckdb.connect(str(out))
    schemas = {
        "orders": "order_id VARCHAR, order_date DATE, region VARCHAR, category VARCHAR, sku VARCHAR, qty INT, revenue DOUBLE, cost DOUBLE, promo_id VARCHAR",
        "logistics": "shipment_id VARCHAR, order_id VARCHAR, carrier VARCHAR, region VARCHAR, ship_date DATE, promised_days INT, actual_days INT, on_time BOOLEAN",
        "returns": "return_id VARCHAR, order_id VARCHAR, return_date DATE, reason VARCHAR",
        "tickets": "ticket_id VARCHAR, order_id VARCHAR, created_date DATE, text VARCHAR",
        "promotions": "promo_id VARCHAR, name VARCHAR, start_date DATE, end_date DATE, category VARCHAR, region VARCHAR, discount_pct DOUBLE",
    }
    for t, sch in schemas.items():
        con.execute(f"CREATE TABLE t_{t} ({sch})")
        cols = [c.split()[0] for c in sch.split(", ")]
        if tables[t]: con.executemany(f"INSERT INTO t_{t} VALUES ({','.join('?'*len(cols))})", [[r[c] for c in cols] for r in tables[t]])
        con.execute(f"CREATE VIEW v_{t} AS SELECT * FROM t_{t}")
    con.close()


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--seed", type=int, default=42)
    ap.add_argument("--out", default=str(ROOT / "data" / "snapshot.duckdb"))
    a = ap.parse_args()
    tables = generate(a.seed)
    write_duckdb(tables, Path(a.out))
    gt = dict(GROUND_TRUTH, seed=a.seed)
    (ROOT / "eval").mkdir(exist_ok=True)
    (ROOT / "eval" / "ground_truth.json").write_text(json.dumps(gt, indent=2) + "\n")
    print({k: len(v) for k, v in tables.items()})


if __name__ == "__main__":
    main()
